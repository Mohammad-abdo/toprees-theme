/**
 * Render an SVG icon by key.
 *
 * @param string $name Icon key.
 * @param array  $args Optional: class, size.
 * @return string
 */
function tk_icon( $name, $args = array() ) {
	$class = isset( $args['class'] ) ? $args['class'] : 'tk-icon';
	$size  = isset( $args['size'] ) ? (int) $args['size'] : 24;
	$icons = tk_icon_paths();
	$path  = isset( $icons[ $name ] ) ? $icons[ $name ] : $icons['sparkles'];

	return sprintf(
		'<svg class="%1$s" width="%2$d" height="%2$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%3$s</svg>',
		esc_attr( $class ),
		$size,
		$path
	);
}

